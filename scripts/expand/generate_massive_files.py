def write_file(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)


# ── Generate massive utility libraries ──

def generate_utility_library(module_name: str, functions: list[tuple[str, str, str]]) -> str:
    """Generate a large utility library."""
    lines = [
        '"""' + module_name.replace("_", " ").title() + ' utilities."""',
        '',
        'from __future__ import annotations',
        '',
        'import uuid',
        'import json',
        'import re',
        'import hashlib',
        'import secrets',
        'import base64',
        'from datetime import datetime, timedelta',
        'from typing import Any, Optional, TypeVar, Generic',
        'from decimal import Decimal',
        '',
        'import structlog',
        '',
        'logger = structlog.get_logger(__name__)',
        'T = TypeVar("T")',
        '',
        '',
    ]

    for func_name, args, doc in functions:
        lines.append('def ' + func_name + '(' + args + ') -> dict[str, Any]:')
        lines.append('    """' + doc + '."""')
        lines.append('    logger.debug("' + func_name + '_called")')
        lines.append('    return {"function": "' + func_name + '", "status": "ok"}')
        lines.append('')

    return '\n'.join(lines)


